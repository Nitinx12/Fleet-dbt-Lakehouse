#!/usr/bin/env bash
# protect_env.sh - Prevent .env files from being committed
# Usage: ./protect_env.sh [--install] [--check]

set -euo pipefail

PROTECTED_PATTERNS=(
    '(^|/)\.env$'
    '(^|/)\.env\.[^/]+$'
    '(^|/)[^/]*\.env$'
    '(^|/)[^/]*\.pem$'
    '(^|/)[^/]*\.key$'
    '(^|/)[^/]*\.crt$'
    '(^|/)[^/]*\.p12$'
    '(^|/)[^/]*\.pfx$'
    '(^|/)id_rsa[^/]*$'
    '(^|/)id_ed25519[^/]*$'
    '(^|/)[^/]*\.secret$'
    '(^|/)[^/]*\.token$'
)

is_protected_path() {
    local path="$1" pattern
    if [[ "$path" == ".env.example" || "$path" == */.env.example ]]; then
        return 1
    fi
    for pattern in "${PROTECTED_PATTERNS[@]}"; do
        if [[ "$path" =~ $pattern ]]; then
            return 0
        fi
    done
    return 1
}

check_paths() {
    local title="$1" source="$2" path violations=0
    echo "$title"
    while IFS= read -r path; do
        [[ -n "$path" ]] || continue
        if is_protected_path "$path"; then
            echo "ERROR: Protected file detected: $path"
            violations=$((violations + 1))
        fi
    done < <("$source")
    return "$violations"
}

check_staged() {
    check_paths "Checking staged files for secrets..." git_diff_cached_names
}

check_committed() {
    check_paths "Checking committed files for secrets..." git_ls_files
}

git_diff_cached_names() {
    git diff --cached --name-only
}

git_ls_files() {
    git ls-files
}

scan_content() {
    local violations=0 pattern diff
    echo "Scanning file content for potential secrets..."

    local secret_patterns=(
        'password[[:space:]]*=[[:space:]]*[^#[:space:]]{8,}'
        'secret[[:space:]]*=[[:space:]]*[^#[:space:]]{16,}'
        'token[[:space:]]*=[[:space:]]*[^#[:space:]]{16,}'
        'api[_-]?key[[:space:]]*=[[:space:]]*[^#[:space:]]{16,}'
        'private[_-]?key'
        '-----BEGIN (RSA |EC |OPENSSH )?PRIVATE KEY-----'
        'mongodb://[^:]+:[^@]+@'
        'postgresql://[^:]+:[^@]+@'
        'mysql://[^:]+:[^@]+@'
        'redis://:[^@]+@'
    )

    diff="$(git diff --cached)"
    for pattern in "${secret_patterns[@]}"; do
        if printf '%s\n' "$diff" | grep -iE -- "$pattern" >/dev/null; then
            echo "WARNING: Potential secret detected in staged changes (pattern: $pattern)"
            violations=$((violations + 1))
        fi
    done

    return "$violations"
}

install_hook() {
    local hook_file=".git/hooks/pre-commit"
    cat > "$hook_file" <<'EOF'
#!/usr/bin/env bash
# Auto-generated by protect_env.sh --install
set -euo pipefail
exec "$(git rev-parse --show-toplevel)/helpers/protect_env.sh" --check
EOF
    chmod +x "$hook_file"
    echo "Installed pre-commit hook at $hook_file"
}

main() {
    case "${1:-}" in
        --install)
            install_hook
            ;;
        --check|"")
            check_staged || exit 1
            check_committed || exit 1
            scan_content || exit 1
            echo "All checks passed."
            ;;
        *)
            echo "Usage: $0 [--install|--check]"
            echo "  --install  Install as git pre-commit hook"
            echo "  --check    Run checks (default)"
            exit 1
            ;;
    esac
}

main "$@"
